"""Database access for PostgreSQL production and SQLite local development.

Queries in the app use qmark parameters and rows accessible by name or position.
Only internal SQL uses this adapter; values are always passed separately.
"""
import sqlite3
import re
import time
from pathlib import Path

import psycopg
from psycopg import sql


INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
SCHEMA_VERSION = 3
# All domain writes in this single-studio app share a transaction lock. This
# preserves cross-class overlap, membership, and last-seat rules across workers.
WRITE_LOCK = 704319820


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


class Connection:
    def __init__(self, config):
        self.postgres = bool(config.get('DATABASE_URL'))
        self.write_locked = False
        if self.postgres:
            tls = {'sslmode': config.get('DATABASE_SSLMODE', 'require')} if config.get('APP_ENV') == 'production' else {}
            self.raw = psycopg.connect(config['DATABASE_URL'], row_factory=row_factory,
                                       connect_timeout=10, application_name='nf-hybrid-portal',
                                       options='-c statement_timeout=20000 -c lock_timeout=15000', **tls)
            if config.get('DATABASE_SCHEMA'):
                schema = config['DATABASE_SCHEMA']
                if not re.fullmatch(r'[a-z_][a-z0-9_]*', schema):
                    raise ValueError('Invalid database schema.')
                self.raw.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(schema)))
        else:
            Path(config['DATABASE']).parent.mkdir(parents=True, exist_ok=True)
            self.raw = sqlite3.connect(config['DATABASE'], timeout=20)
            self.raw.row_factory = sqlite3.Row
            self.raw.execute('PRAGMA foreign_keys=ON')
            self.raw.execute('PRAGMA journal_mode=WAL')

    def execute(self, query, params=None):
        if self.postgres and params is not None:
            query = query.replace('%', '%%').replace('?', '%s')
        return self.raw.execute(query, params) if params is not None else self.raw.execute(query)

    def begin_write(self):
        if not self.write_locked:
            if self.postgres:
                self.execute('SELECT pg_advisory_xact_lock(?)', (WRITE_LOCK,))
            else:
                self.execute('BEGIN IMMEDIATE')
            self.write_locked = True

    def commit(self):
        self.raw.commit()
        self.write_locked = False

    def rollback(self):
        self.raw.rollback()
        self.write_locked = False

    def close(self):
        self.raw.close()  # Also rolls back any uncommitted request or failed check.

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.rollback() if exc_type else self.commit()


def migrate(connection):
    connection.begin_write()
    connection.execute('CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY,applied_at BIGINT NOT NULL)')
    current = connection.execute('SELECT COALESCE(MAX(version),0) FROM schema_migrations').fetchone()[0]
    if current > SCHEMA_VERSION:
        raise RuntimeError('Database schema is newer than this app. Deploy a compatible version.')
    migrations = Path(__file__).parent / 'migrations'
    for version, filename in ((1, '001_initial.sql'), (2, '002_sessions_and_login_limits.sql'),
                              (3, '003_usernames_and_temporary_passwords.sql')):
        if current >= version:
            continue
        source = (migrations / filename).read_text(encoding='utf-8')
        if connection.postgres:
            # Only these four tables generate their own IDs. Foreign keys do not.
            for table in ('users', 'classes', 'bookings', 'progress'):
                source = source.replace(f'{table}(id INTEGER PRIMARY KEY',
                                        f'{table}(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            source = source.replace('weight REAL', 'weight DOUBLE PRECISION')
        for statement in source.split(';'):
            if statement.strip():
                connection.execute(statement)
        if version == 3:
            from accounts import generate_username
            for user in connection.execute('SELECT id,name FROM users ORDER BY id').fetchall():
                connection.execute('UPDATE users SET username=? WHERE id=?',
                                   (generate_username(connection, user['name']), user['id']))
        connection.execute('INSERT INTO schema_migrations(version,applied_at) VALUES(?,?)', (version, int(time.time())))
    # Caller commits bootstrap and migration together under the same write lock.


def consume_login_attempt(connection, bucket, maximum, stamp):
    result = connection.execute('''INSERT INTO login_attempts(bucket,window_start,attempts) VALUES(?,?,1)
        ON CONFLICT(bucket) DO UPDATE SET
        attempts=CASE WHEN login_attempts.window_start<=? THEN 1 ELSE login_attempts.attempts+1 END,
        window_start=CASE WHEN login_attempts.window_start<=? THEN excluded.window_start ELSE login_attempts.window_start END
        RETURNING attempts''', (bucket, stamp, stamp - 300, stamp - 300)).fetchone()[0]
    return result <= maximum
